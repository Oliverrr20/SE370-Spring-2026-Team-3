package backend;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import org.mindrot.jbcrypt.BCrypt;

@Entity
public class Client {
    //variables
    @Id
    @GeneratedValue(strategy = GenerationType.AUTO)
    int UserID;        //id will be generated by backend
    String FirstName;   //Required
    String LastName;    //Required
    String UserRole;    //Required
    String DOB;         //Required
    String Phone;       //Required
    String Email;       //Optional
    String Pass;        //Required
    String LastLogin;   //Set by functions
    String LastUpdated; //Set by functions
    //empty constructor
    public Client(){}
    //constructor with basic required fields
    public Client(String fn, String ln, String ur, String dob, String p, String pass) {
        FirstName = fn; //set first name
        LastName = ln; //set last name
        UserRole = ur; //set user role
        DOB = dob; //set dob
        Phone = p;     //set phone

        //hashing!
        Pass = BCrypt.hashpw(pass, BCrypt.gensalt());
    }
    //constructors with optional field
    public Client(String fn, String ln, String ur, String dob, String p, String e, String pass) {
        FirstName = fn; //set first name
        LastName = ln; //set last name
        UserRole = ur; //set user role
        DOB = dob; //set dob
        Phone = p;     //set z
        Email = e; //set email

        //hasing!
        Pass = BCrypt.hashpw(pass, BCrypt.gensalt());    //set password
    }
    public int getClientID() {
        return UserID;
    }
    public void setClientID(int uID) {
        UserID = uID;
    }
    public String getPass() {
        return Pass;
    }
}
